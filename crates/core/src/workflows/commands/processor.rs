/// Command processor for routing workflow commands to handlers
///
/// Processes commands generated by workflow execution and routes them
/// to the appropriate handlers (child workflow manager, task queue, timer service, etc.).
pub struct CommandProcessor {
    /// Journal service for appending execution journal entries
    journal_service: Arc<JournalService>,

    /// Child workflow manager for child workflow orchestration
    child_workflow_manager: Arc<ChildWorkflowManager>,

    /// Event bus for publishing workflow lifecycle events
    event_bus: Arc<EventBus>,

    /// Polling manager for notifying waiting services
    polling_manager: Option<Arc<crate::engine::dispatch::PollingManager>>,

    /// Execution log repository for step result persistence
    execution_log_repository: Arc<dyn ExecutionLogRepository>,

    /// Task execution repository for task lifecycle tracking
    task_execution_repository: Arc<TaskExecutionRepository>,

    /// Workflow execution repository for workflow status updates
    workflow_execution_repository: Arc<WorkflowExecutionRepository>,

    /// Workflow coordinator for task orchestration (connects to outbox queue)
    coordinator: Option<Arc<crate::engine::WorkflowCoordinator>>,

    /// Workflow execution logs repository for user-facing logs
    logs_repository: Arc<WorkflowExecutionLogsRepository>,

    /// How large a payload a command may carry.
    payload_limits: PayloadLimits,
}

/// The FailWorkflow command the engine issues on a workflow's behalf when one
/// of its commands is refused as invalid.
fn invalid_command_failure(reason: &str) -> Command {
    use orcher_proto::orcher::v1::{command::Attributes, FailWorkflowCommandAttributes, Failure};
    Command {
        command_type: CommandType::FailWorkflow as i32,
        attributes: Some(Attributes::FailWorkflow(FailWorkflowCommandAttributes {
            failure: Some(Failure {
                message: format!("the engine refused a command: {reason}"),
                source: "engine".to_string(),
                failure_type: "InvalidCommand".to_string(),
                ..Default::default()
            }),
        })),
    }
}

/// The payload `command` carries that is over the limit, as the reason to fail
/// the workflow with; `None` when every payload it carries fits.
///
/// Every payload a workflow produces passes through here: a task's input, a
/// child's input, an event it sends, a step it recorded, and its own result.
/// Accepted, a payload over the limit would be stored and then carried in every
/// activation after, which could no longer reach the worker. Replay re-issues
/// the same command, so the workflow fails at once rather than retrying it.
pub(crate) fn oversized_payload(command: &Command, limits: &PayloadLimits) -> Option<String> {
    use orcher_proto::orcher::v1::command::Attributes;
    let (what, size) = match command.attributes.as_ref()? {
        Attributes::ScheduleTask(a) => {
            (format!("the input of task {:?}", a.task_id), a.input.len())
        }
        Attributes::StartChildWorkflow(a) => (
            format!("the input of child workflow {:?}", a.workflow_id),
            a.input.len(),
        ),
        Attributes::SendEvent(a) => (
            format!("the payload of event {:?}", a.event_name),
            a.payload.len(),
        ),
        Attributes::RecordStepResult(a) => (
            format!("the result of step {:?}", a.step_name),
            a.result.len(),
        ),
        Attributes::RestartFresh(a) => ("the input of the fresh run".to_string(), a.input.len()),
        Attributes::CompleteWorkflow(a) => ("the workflow result".to_string(), a.result.len()),
        _ => return None,
    };
    limits.check(&what, size).err()
}

/// The FailWorkflow command the engine issues on a workflow's behalf when one
/// of its commands carries a payload over the limit.
fn payload_too_large_failure(reason: &str) -> Command {
    use orcher_proto::orcher::v1::{command::Attributes, FailWorkflowCommandAttributes, Failure};
    Command {
        command_type: CommandType::FailWorkflow as i32,
        attributes: Some(Attributes::FailWorkflow(FailWorkflowCommandAttributes {
            failure: Some(Failure {
                message: reason.to_string(),
                source: "engine".to_string(),
                failure_type: PAYLOAD_TOO_LARGE.to_string(),
                non_retryable: true,
                ..Default::default()
            }),
        })),
    }
}

/// `commands`, or in their place the one command that fails the workflow when
/// any of them carries a payload over the limit. None of the batch is applied
/// then: what it scheduled would only be cancelled again.
fn screen_payloads(
    workflow_id: &str,
    execution_id: &str,
    commands: Vec<Command>,
    limits: &PayloadLimits,
) -> Vec<Command> {
    match commands
        .iter()
        .find_map(|command| oversized_payload(command, limits))
    {
        Some(reason) => {
            warn!(
                workflow_id = %workflow_id,
                execution_id = %execution_id,
                reason = %reason,
                "A command carries a payload over the limit; failing the workflow"
            );
            vec![payload_too_large_failure(&reason)]
        }
        None => commands,
    }
}

/// The failure type a FailWorkflow command reports, if it names one.
///
/// Carried out of command processing so the retry decision made when the
/// failure is recorded can honour a policy's non-retryable error types.
fn fail_workflow_failure_type(command: &Command) -> Option<String> {
    use orcher_proto::orcher::v1::command::Attributes;
    match command.attributes.as_ref() {
        Some(Attributes::FailWorkflow(attrs)) => attrs
            .failure
            .as_ref()
            .map(|f| f.failure_type.clone())
            .filter(|t| !t.is_empty()),
        _ => None,
    }
}

/// Whether a FailWorkflow command's failure was raised as non-retryable.
///
/// Carried out of command processing with the failure type, for the same
/// retry decision.
fn fail_workflow_non_retryable(command: &Command) -> bool {
    use orcher_proto::orcher::v1::command::Attributes;
    match command.attributes.as_ref() {
        Some(Attributes::FailWorkflow(attrs)) => {
            attrs.failure.as_ref().is_some_and(|f| f.non_retryable)
        }
        _ => false,
    }
}

impl CommandProcessor {
    /// Create a new command processor
    ///
    /// # Arguments
    ///
    /// * `journal_service` - Service for appending journal entries
    /// * `child_workflow_manager` - Manager for child workflow orchestration
    /// * `event_bus` - Event bus for publishing lifecycle events
    /// * `execution_log_repository` - Repository for step result persistence
    /// * `task_execution_repository` - Repository for task lifecycle tracking
    pub fn new(
        journal_service: Arc<JournalService>,
        child_workflow_manager: Arc<ChildWorkflowManager>,
        event_bus: Arc<EventBus>,
        execution_log_repository: Arc<dyn ExecutionLogRepository>,
        task_execution_repository: Arc<TaskExecutionRepository>,
        workflow_execution_repository: Arc<WorkflowExecutionRepository>,
        pool: Arc<sqlx::PgPool>,
    ) -> Self {
        let logs_repository = Arc::new(WorkflowExecutionLogsRepository::new((*pool).clone()));
        Self {
            journal_service,
            child_workflow_manager,
            event_bus,
            polling_manager: None,
            execution_log_repository,
            task_execution_repository,
            workflow_execution_repository,
            coordinator: None,
            logs_repository,
            payload_limits: PayloadLimits::default(),
        }
    }

    /// How large a payload a command may carry. [`PayloadLimits::default`]
    /// unless set.
    pub fn with_payload_limits(mut self, limits: PayloadLimits) -> Self {
        self.payload_limits = limits;
        self
    }

    /// Set the polling manager for notifying waiting services
    pub fn with_polling_manager(
        mut self,
        polling_manager: Arc<crate::engine::dispatch::PollingManager>,
    ) -> Self {
        self.polling_manager = Some(polling_manager);
        self
    }

    /// Set the workflow coordinator for task orchestration
    pub fn with_coordinator(
        mut self,
        coordinator: Arc<crate::engine::WorkflowCoordinator>,
    ) -> Self {
        self.coordinator = Some(coordinator);
        self
    }

    /// Process a list of commands from workflow execution
    ///
    /// Commands are processed in order. If any command fails, processing stops
    /// and an error is returned.
    #[instrument(skip(self, commands), fields(
        workflow_id = %workflow_id,
        execution_id = %execution_id,
        command_count = commands.len()
    ))]
    pub async fn process_commands(
        &self,
        workflow_id: &str,
        execution_id: &str,
        namespace: &str,
        commands: Vec<Command>,
    ) -> OrcherResult<()> {
        if commands.is_empty() {
            debug!(
                workflow_id = %workflow_id,
                execution_id = %execution_id,
                "No commands to process"
            );
            return Ok(());
        }

        debug!(
            workflow_id = %workflow_id,
            execution_id = %execution_id,
            namespace = %namespace,
            command_count = commands.len(),
            "Processing commands"
        );
        let commands = screen_payloads(workflow_id, execution_id, commands, &self.payload_limits);

        // Process each command in order
        for (index, command) in commands.iter().enumerate() {
            debug!(
                workflow_id = %workflow_id,
                execution_id = %execution_id,
                command_index = index,
                command_type = ?command.command_type,
                "Processing command"
            );

            if let Err(e) = self
                .process_single_command(workflow_id, execution_id, namespace, command)
                .await
            {
                error!(
                    workflow_id = %workflow_id,
                    execution_id = %execution_id,
                    command_index = index,
                    error = %e,
                    "Failed to process command"
                );
                return Err(e);
            }
        }

        debug!(
            workflow_id = %workflow_id,
            execution_id = %execution_id,
            "CMD_PROCESSOR: All commands processed successfully"
        );

        Ok(())
    }

    /// Process commands and return result with scheduled tasks for eager dispatch
    #[instrument(skip(self, commands), fields(
        workflow_id = %workflow_id,
        execution_id = %execution_id,
        namespace = %namespace,
        command_count = commands.len()
    ))]
    pub async fn process_commands_with_result(
        &self,
        workflow_id: &str,
        execution_id: &str,
        namespace: &str,
        commands: Vec<Command>,
    ) -> OrcherResult<CommandProcessingResult> {
        let mut result = CommandProcessingResult::new();

        if commands.is_empty() {
            debug!(
                workflow_id = %workflow_id,
                execution_id = %execution_id,
                "No commands to process"
            );
            return Ok(result);
        }

        debug!(
            workflow_id = %workflow_id,
            execution_id = %execution_id,
            namespace = %namespace,
            command_count = commands.len(),
            "Processing commands"
        );
        let commands = screen_payloads(workflow_id, execution_id, commands, &self.payload_limits);

        // Process each command in order
        for (index, command) in commands.iter().enumerate() {
            debug!(
                workflow_id = %workflow_id,
                execution_id = %execution_id,
                command_index = index,
                command_type = ?command.command_type,
                "Processing command"
            );

            // Whether a completion was already applied by an earlier command
            // in this batch; the flags below are set before this one runs.
            let completed_earlier = result.workflow_completed;

            // Check command type for result flags
            if let Ok(cmd_type) = CommandType::try_from(command.command_type) {
                match cmd_type {
                    CommandType::CompleteWorkflow => {
                        result.workflow_completed = true;
                    }
                    CommandType::FailWorkflow => {
                        result.workflow_failed = true;
                        result.failure_type = fail_workflow_failure_type(command);
                        result.non_retryable = fail_workflow_non_retryable(command);
                    }
                    CommandType::CancelWorkflow => {
                        result.workflow_cancelled = true;
                    }
                    _ => {}
                }
            }

            // Route command and capture scheduled tasks
            match self
                .process_single_command_with_result(workflow_id, execution_id, namespace, command)
                .await
            {
                Ok(Some(task_execution)) => {
                    debug!(
                        workflow_id = %workflow_id,
                        execution_id = %execution_id,
                        task_id = %task_execution.task_id,
                        task_execution_id = %task_execution.id,
                        "EAGER_TASK: Captured scheduled task for eager return"
                    );
                    result.scheduled_tasks.push(task_execution);
                    result.commands_processed += 1;
                }
                Ok(None) => {
                    result.commands_processed += 1;
                }
                // A command refused as invalid is refused again on every
                // replay, because replay re-issues the same command. Returned
                // as an error it failed the RPC, the worker dropped the
                // completion, the activation was handed out again, and the
                // workflow looped with nothing to say why. It fails the
                // workflow instead, with the reason, the way the SDK fails a
                // workflow whose commands it cannot convert.
                Err(OrcherError::InvalidInput { message, field }) if !completed_earlier => {
                    let reason = match field {
                        Some(field) => format!("{field}: {message}"),
                        None => message,
                    };
                    warn!(
                        workflow_id = %workflow_id,
                        execution_id = %execution_id,
                        command_index = index,
                        reason = %reason,
                        "Command refused as invalid; failing the workflow that issued it"
                    );
                    self.process_single_command(
                        workflow_id,
                        execution_id,
                        namespace,
                        &invalid_command_failure(&reason),
                    )
                    .await?;
                    result.workflow_completed = false;
                    result.workflow_failed = true;
                    result.failure_type = Some("InvalidCommand".to_string());
                    // Nothing scheduled by this batch is handed out for a
                    // workflow that has just failed.
                    result.scheduled_tasks.clear();
                    return Ok(result);
                }
                Err(e) => {
                    error!(
                        workflow_id = %workflow_id,
                        execution_id = %execution_id,
                        command_index = index,
                        error = %e,
                        "Failed to process command"
                    );
                    return Err(e);
                }
            }
        }

        debug!(
            workflow_id = %workflow_id,
            execution_id = %execution_id,
            commands_processed = result.commands_processed,
            scheduled_tasks = result.scheduled_tasks.len(),
            workflow_completed = result.workflow_completed,
            workflow_failed = result.workflow_failed,
            "CMD_PROCESSOR: process_commands_with_result completed"
        );

        Ok(result)
    }

    /// Process a single command and optionally return a scheduled task
    async fn process_single_command_with_result(
        &self,
        workflow_id: &str,
        execution_id: &str,
        namespace: &str,
        command: &Command,
    ) -> OrcherResult<Option<TaskExecution>> {
        match CommandType::try_from(command.command_type) {
            Ok(CommandType::ScheduleTask) => {
                handlers::task::handle_schedule_task_with_result(
                    &self.journal_service,
                    &self.task_execution_repository,
                    &self.coordinator,
                    &self.logs_repository,
                    workflow_id,
                    execution_id,
                    namespace,
                    command,
                )
                .await
            }
            _ => {
                self.process_single_command(workflow_id, execution_id, namespace, command)
                    .await?;
                Ok(None)
            }
        }
    }

    /// Process a single command
    #[instrument(skip(self, command), fields(
        workflow_id = %workflow_id,
        execution_id = %execution_id,
        command_type = ?command.command_type
    ))]
    async fn process_single_command(
        &self,
        workflow_id: &str,
        execution_id: &str,
        namespace: &str,
        command: &Command,
    ) -> OrcherResult<()> {
        let cmd_type_str = CommandType::try_from(command.command_type)
            .map(|t| format!("{:?}", t))
            .unwrap_or_else(|_| format!("Unknown({})", command.command_type));

        debug!(
            workflow_id = %workflow_id,
            execution_id = %execution_id,
            command_type = %cmd_type_str,
            "CMD_PROCESSOR: Processing single command"
        );

        match CommandType::try_from(command.command_type) {
            Ok(CommandType::StartChildWorkflow) => {
                handlers::child::handle_start_child_workflow(
                    &self.child_workflow_manager,
                    &self.polling_manager,
                    workflow_id,
                    execution_id,
                    namespace,
                    command,
                )
                .await
            }
            Ok(CommandType::ScheduleTask) => {
                handlers::task::handle_schedule_task(
                    &self.journal_service,
                    &self.task_execution_repository,
                    &self.coordinator,
                    &self.polling_manager,
                    &self.logs_repository,
                    workflow_id,
                    execution_id,
                    namespace,
                    command,
                )
                .await
            }
            Ok(CommandType::StartTimer) => {
                handlers::timer::handle_start_timer(
                    &self.journal_service,
                    &self.coordinator,
                    workflow_id,
                    execution_id,
                    command,
                )
                .await
            }
            Ok(CommandType::CancelTimer) => {
                handlers::timer::handle_cancel_timer(
                    &self.journal_service,
                    workflow_id,
                    execution_id,
                    command,
                )
                .await
            }
            Ok(CommandType::CompleteWorkflow) => {
                handlers::workflow::handle_complete_workflow(
                    &self.journal_service,
                    &self.event_bus,
                    &self.workflow_execution_repository,
                    &self.execution_log_repository,
                    &self.logs_repository,
                    workflow_id,
                    execution_id,
                    command,
                )
                .await
            }
            Ok(CommandType::FailWorkflow) => {
                handlers::workflow::handle_fail_workflow(
                    &self.journal_service,
                    &self.event_bus,
                    &self.workflow_execution_repository,
                    &self.logs_repository,
                    workflow_id,
                    execution_id,
                    command,
                )
                .await
            }
            Ok(CommandType::CancelWorkflow) => {
                handlers::workflow::handle_cancel_workflow(
                    &self.journal_service,
                    &self.event_bus,
                    &self.workflow_execution_repository,
                    workflow_id,
                    execution_id,
                    command,
                )
                .await
            }
            Ok(CommandType::RestartFresh) => {
                handlers::workflow::handle_restart_fresh(
                    &self.journal_service,
                    &self.workflow_execution_repository,
                    &self.child_workflow_manager,
                    workflow_id,
                    execution_id,
                    command,
                )
                .await
            }
            Ok(CommandType::RequestCancelTask) => {
                handlers::task::handle_request_cancel_task(
                    &self.journal_service,
                    &self.task_execution_repository,
                    workflow_id,
                    execution_id,
                    command,
                )
                .await
            }
            Ok(CommandType::CancelChildWorkflow) => {
                handlers::child::handle_cancel_child_workflow(
                    &self.child_workflow_manager,
                    workflow_id,
                    execution_id,
                    command,
                )
                .await
            }
            Ok(CommandType::SendEvent) => {
                handlers::event::handle_send_event(
                    &self.journal_service,
                    &self.workflow_execution_repository,
                    self.polling_manager.as_ref(),
                    workflow_id,
                    execution_id,
                    command,
                )
                .await
            }
            Ok(CommandType::RequestCancellation) => {
                handlers::event::handle_request_cancellation(
                    &self.journal_service,
                    workflow_id,
                    execution_id,
                    command,
                )
                .await
            }
            Ok(CommandType::QueryChildWorkflow) => {
                handlers::child::handle_query_child_workflow(
                    &self.child_workflow_manager,
                    workflow_id,
                    execution_id,
                    command,
                )
                .await
            }
            Ok(CommandType::RecordStepResult) => {
                handlers::task::handle_record_step_result(
                    &self.journal_service,
                    &self.execution_log_repository,
                    &self.logs_repository,
                    workflow_id,
                    execution_id,
                    command,
                )
                .await
            }
            Ok(CommandType::UpsertLabels) => self.handle_upsert_labels(execution_id, command).await,
            Ok(CommandType::Unspecified) | Err(_) => {
                warn!(
                    workflow_id = %workflow_id,
                    execution_id = %execution_id,
                    command_type = command.command_type,
                    "Unknown or unspecified command type"
                );
                // Not InvalidInput: a command type this engine does not know
                // can come from an SDK newer than it, as during a rolling
                // upgrade, and a newer engine would accept it. That is left
                // to retry rather than failing the workflow.
                Err(OrcherError::internal(format!(
                    "Unknown command type: {} (not supported by this engine version)",
                    command.command_type
                )))
            }
        }
    }

    /// Handle UpsertLabels command — merge new attributes into existing ones
    async fn handle_upsert_labels(
        &self,
        execution_id: &str,
        command: &Command,
    ) -> OrcherResult<()> {
        let attrs = command
            .attributes
            .as_ref()
            .and_then(|a| {
                if let orcher_proto::orcher::v1::command::Attributes::UpsertLabels(ref sa) = a {
                    Some(&sa.labels)
                } else {
                    None
                }
            })
            .ok_or_else(|| OrcherError::invalid_input("Missing upsert_labels attributes"))?;

        let json_attrs = serde_json::to_value(attrs).unwrap_or_default();

        self.workflow_execution_repository
            .update_labels(execution_id, &json_attrs)
            .await?;

        debug!(
            execution_id = %execution_id,
            attr_count = attrs.len(),
            "Upserted labels"
        );

        Ok(())
    }
}

