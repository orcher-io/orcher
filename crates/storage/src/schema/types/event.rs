//! Event sourcing storage types.

use orcher_common::types::identifiers::{
    AggregateId, CorrelationId, EventId, Identifier, NodeId, RequestId, ScheduleId, SnapshotId,
    TaskId, UserId, WorkerId, WorkflowId,
};
use orcher_common::types::time::Timestamptz;
use serde::{Deserialize, Serialize};

/// Format: `{category}:{id}` (e.g., "task:550e8400...")
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct StreamId {
    pub category: String,
    pub id: String,
}

impl StreamId {
    pub fn new(category: impl Into<String>, id: impl Into<String>) -> Self {
        Self {
            category: category.into(),
            id: id.into(),
        }
    }

    pub fn from_aggregate_id(aggregate_id: &AggregateId) -> Self {
        match aggregate_id {
            AggregateId::Task(id) => Self::new("task", id.as_uuid().to_string()),
            AggregateId::Worker(id) => Self::new("worker", id.as_uuid().to_string()),
            AggregateId::Workflow(id) => Self::new("workflow", id.as_uuid().to_string()),
            AggregateId::Schedule(id) => Self::new("schedule", id.as_uuid().to_string()),
            AggregateId::User(id) => Self::new("user", id.as_uuid().to_string()),
            AggregateId::Node(id) => Self::new("node", id.as_uuid().to_string()),
        }
    }

    pub fn to_aggregate_id(&self) -> Option<AggregateId> {
        let uuid = uuid::Uuid::parse_str(&self.id).ok()?;
        match self.category.as_str() {
            "task" => Some(AggregateId::Task(TaskId::from_uuid(uuid))),
            "worker" => Some(AggregateId::Worker(WorkerId::from_uuid(uuid))),
            "workflow" => Some(AggregateId::Workflow(WorkflowId::from_uuid(uuid))),
            "schedule" => Some(AggregateId::Schedule(ScheduleId::from_uuid(uuid))),
            "user" => Some(AggregateId::User(UserId::from_uuid(uuid))),
            "node" => Some(AggregateId::Node(NodeId::from_uuid(uuid))),
            _ => None,
        }
    }

    pub fn parse(s: &str) -> Result<Self, String> {
        let parts: Vec<&str> = s.splitn(2, ':').collect();
        if parts.len() == 2 {
            Ok(Self::new(parts[0], parts[1]))
        } else {
            Err(format!("Invalid stream_id format: {}", s))
        }
    }

    pub fn as_string(&self) -> String {
        format!("{}:{}", self.category, self.id)
    }
}

impl std::fmt::Display for StreamId {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}:{}", self.category, self.id)
    }
}

impl std::str::FromStr for StreamId {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        Self::parse(s)
    }
}

// SQLx support
#[cfg(feature = "postgres")]
impl sqlx::Type<sqlx::Postgres> for StreamId {
    fn type_info() -> sqlx::postgres::PgTypeInfo {
        <String as sqlx::Type<sqlx::Postgres>>::type_info()
    }
}

#[cfg(feature = "postgres")]
impl<'r> sqlx::Decode<'r, sqlx::Postgres> for StreamId {
    fn decode(
        value: sqlx::postgres::PgValueRef<'r>,
    ) -> Result<Self, Box<dyn std::error::Error + 'static + Send + Sync>> {
        let s = <String as sqlx::Decode<sqlx::Postgres>>::decode(value)?;
        Self::parse(&s).map_err(|e| e.into())
    }
}

#[cfg(feature = "postgres")]
impl<'q> sqlx::Encode<'q, sqlx::Postgres> for StreamId {
    fn encode_by_ref(
        &self,
        buf: &mut sqlx::postgres::PgArgumentBuffer,
    ) -> Result<sqlx::encode::IsNull, Box<dyn std::error::Error + Send + Sync>> {
        let s = self.as_string();
        <String as sqlx::Encode<sqlx::Postgres>>::encode(s, buf)
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[cfg_attr(feature = "postgres", derive(sqlx::FromRow))]
pub struct StoredEvent {
    /// Auto-incremented
    pub event_id: i64,
    pub organization_id: Option<uuid::Uuid>,
    pub stream_id: StreamId,
    pub stream_category: String,
    /// e.g., "TaskSubmitted", "WorkflowStarted" (append V2 for schema evolution)
    pub event_type: String,
    pub payload: serde_json::Value,
    pub metadata: serde_json::Value,
    /// Business time
    pub timestamp: Timestamptz,
    /// Monotonically increasing within stream
    pub stream_position: i64,
    /// Total ordering across all streams
    pub global_position: i64,
    pub causation_id: Option<EventId>,
    pub correlation_id: Option<CorrelationId>,
    pub created_at: Timestamptz,
}

impl StoredEvent {
    pub fn new(
        stream_id: StreamId,
        event_type: String,
        payload: serde_json::Value,
        stream_position: i64,
    ) -> Self {
        let now = Timestamptz::now();
        let stream_category = stream_id.category.clone();
        Self {
            event_id: 0, // Auto-generated by database
            organization_id: None,
            stream_id,
            stream_category,
            event_type,
            payload,
            metadata: serde_json::json!({}),
            timestamp: now,
            stream_position,
            global_position: 0, // Auto-generated by database
            causation_id: None,
            correlation_id: None,
            created_at: now,
        }
    }

    pub fn new_with_org(
        organization_id: uuid::Uuid,
        stream_id: StreamId,
        event_type: String,
        payload: serde_json::Value,
        stream_position: i64,
    ) -> Self {
        let now = Timestamptz::now();
        let stream_category = stream_id.category.clone();
        Self {
            event_id: 0, // Auto-generated by database
            organization_id: Some(organization_id),
            stream_id,
            stream_category,
            event_type,
            payload,
            metadata: serde_json::json!({}),
            timestamp: now,
            stream_position,
            global_position: 0, // Auto-generated by database
            causation_id: None,
            correlation_id: None,
            created_at: now,
        }
    }

    pub fn from_aggregate(
        aggregate_id: AggregateId,
        event_type: String,
        payload: serde_json::Value,
        stream_position: i64,
    ) -> Self {
        let stream_id = StreamId::from_aggregate_id(&aggregate_id);
        Self::new(stream_id, event_type, payload, stream_position)
    }

    pub fn aggregate_id(&self) -> Option<AggregateId> {
        self.stream_id.to_aggregate_id()
    }

    pub fn aggregate_type(&self) -> &str {
        &self.stream_category
    }

    pub fn with_metadata(mut self, metadata: EventMetadata) -> Self {
        self.metadata = serde_json::to_value(metadata).unwrap_or_default();
        self
    }

    pub fn with_causation(mut self, causation_id: EventId) -> Self {
        self.causation_id = Some(causation_id);
        self
    }

    pub fn with_correlation(mut self, correlation_id: CorrelationId) -> Self {
        self.correlation_id = Some(correlation_id);
        self
    }

    pub fn with_timestamp(mut self, timestamp: Timestamptz) -> Self {
        self.timestamp = timestamp;
        self
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EventMetadata {
    pub actor: Option<String>,
    pub source: Option<String>,
    pub request_id: Option<RequestId>,
    pub client_ip: Option<String>,
    pub user_agent: Option<String>,
    #[serde(flatten)]
    pub custom: serde_json::Value,
}

impl Default for EventMetadata {
    fn default() -> Self {
        Self {
            actor: None,
            source: None,
            request_id: None,
            client_ip: None,
            user_agent: None,
            custom: serde_json::json!({}),
        }
    }
}

#[derive(Debug, Clone, Default)]
pub struct EventFilter {
    pub stream_id: Option<StreamId>,
    pub stream_category: Option<String>,
    pub event_types: Vec<String>,
    pub after_position: Option<i64>,
    pub before_position: Option<i64>,
    pub after_timestamp: Option<Timestamptz>,
    pub before_timestamp: Option<Timestamptz>,
    pub limit: Option<usize>,
    pub offset: Option<usize>,
}

impl EventFilter {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn with_stream_id(mut self, stream_id: StreamId) -> Self {
        self.stream_id = Some(stream_id);
        self
    }

    pub fn with_stream_category(mut self, category: impl Into<String>) -> Self {
        self.stream_category = Some(category.into());
        self
    }

    pub fn with_event_types(mut self, event_types: Vec<String>) -> Self {
        self.event_types = event_types;
        self
    }

    pub fn after_position(mut self, position: i64) -> Self {
        self.after_position = Some(position);
        self
    }

    pub fn before_position(mut self, position: i64) -> Self {
        self.before_position = Some(position);
        self
    }

    pub fn limit(mut self, limit: usize) -> Self {
        self.limit = Some(limit);
        self
    }

    pub fn offset(mut self, offset: usize) -> Self {
        self.offset = Some(offset);
        self
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[cfg_attr(feature = "postgres", derive(sqlx::FromRow))]
pub struct EventSnapshot {
    pub snapshot_id: SnapshotId,
    pub organization_id: Option<uuid::Uuid>,
    pub stream_id: StreamId,
    pub stream_category: String,
    /// Stream position at which this snapshot was taken
    pub stream_position: i64,
    pub data: serde_json::Value,
    pub metadata: serde_json::Value,
    pub created_at: Timestamptz,
}

impl EventSnapshot {
    pub fn new(stream_id: StreamId, stream_position: i64, data: serde_json::Value) -> Self {
        let stream_category = stream_id.category.clone();
        Self {
            snapshot_id: SnapshotId::generate(),
            organization_id: None,
            stream_id,
            stream_category,
            stream_position,
            data,
            metadata: serde_json::json!({}),
            created_at: Timestamptz::now(),
        }
    }

    pub fn new_with_org(
        organization_id: uuid::Uuid,
        stream_id: StreamId,
        stream_position: i64,
        data: serde_json::Value,
    ) -> Self {
        let stream_category = stream_id.category.clone();
        Self {
            snapshot_id: SnapshotId::generate(),
            organization_id: Some(organization_id),
            stream_id,
            stream_category,
            stream_position,
            data,
            metadata: serde_json::json!({}),
            created_at: Timestamptz::now(),
        }
    }

    pub fn from_aggregate(
        aggregate_id: AggregateId,
        stream_position: i64,
        data: serde_json::Value,
    ) -> Self {
        let stream_id = StreamId::from_aggregate_id(&aggregate_id);
        Self::new(stream_id, stream_position, data)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_stream_id_creation() {
        let stream_id = StreamId::new("task", "123e4567-e89b-12d3-a456-426614174000");
        assert_eq!(stream_id.category, "task");
        assert_eq!(stream_id.id, "123e4567-e89b-12d3-a456-426614174000");
    }

    #[test]
    fn test_stream_id_from_aggregate() {
        let task_id = TaskId::generate();
        let aggregate_id = AggregateId::Task(task_id);
        let stream_id = StreamId::from_aggregate_id(&aggregate_id);

        assert_eq!(stream_id.category, "task");
        assert_eq!(stream_id.id, task_id.as_uuid().to_string());
    }

    #[test]
    fn test_stream_id_to_aggregate() {
        let task_id = TaskId::generate();
        let stream_id = StreamId::new("task", task_id.as_uuid().to_string());

        let aggregate_id = stream_id.to_aggregate_id();
        assert!(aggregate_id.is_some());

        if let Some(AggregateId::Task(parsed_id)) = aggregate_id {
            assert_eq!(parsed_id, task_id);
        } else {
            panic!("Expected Task aggregate ID");
        }
    }

    #[test]
    fn test_stream_id_as_string() {
        let stream_id = StreamId::new("task", "123");
        assert_eq!(stream_id.as_string(), "task:123");
        assert_eq!(stream_id.to_string(), "task:123");
    }

    #[test]
    fn test_stream_id_parse() {
        let stream_id = StreamId::parse("task:123").unwrap();
        assert_eq!(stream_id.category, "task");
        assert_eq!(stream_id.id, "123");

        let result = StreamId::parse("invalid");
        assert!(result.is_err());
    }

    #[test]
    fn test_stream_id_from_str() {
        let stream_id: StreamId = "worker:456".parse().unwrap();
        assert_eq!(stream_id.category, "worker");
        assert_eq!(stream_id.id, "456");
    }

    #[test]
    fn test_stored_event_creation() {
        let stream_id = StreamId::new("task", "123");
        let event = StoredEvent::new(
            stream_id.clone(),
            "TaskSubmitted".to_string(),
            serde_json::json!({"name": "test"}),
            1,
        );

        assert_eq!(event.stream_id, stream_id);
        assert_eq!(event.stream_category, "task");
        assert_eq!(event.event_type, "TaskSubmitted");
        assert_eq!(event.stream_position, 1);
    }

    #[test]
    fn test_stored_event_from_aggregate() {
        let task_id = TaskId::generate();
        let aggregate_id = AggregateId::Task(task_id);
        let event = StoredEvent::from_aggregate(
            aggregate_id,
            "TaskSubmitted".to_string(),
            serde_json::json!({}),
            1,
        );

        assert_eq!(event.stream_category, "task");
        assert_eq!(event.stream_id.category, "task");
        assert_eq!(event.stream_position, 1);
    }

    #[test]
    fn test_stored_event_aggregate_id() {
        let task_id = TaskId::generate();
        let aggregate_id = AggregateId::Task(task_id);
        let event = StoredEvent::from_aggregate(
            aggregate_id,
            "TaskSubmitted".to_string(),
            serde_json::json!({}),
            1,
        );

        let extracted = event.aggregate_id();
        assert!(extracted.is_some());

        if let Some(AggregateId::Task(parsed_id)) = extracted {
            assert_eq!(parsed_id, task_id);
        } else {
            panic!("Expected Task aggregate ID");
        }
    }

    #[test]
    fn test_event_filter_builder() {
        let stream_id = StreamId::new("task", "123");
        let filter = EventFilter::new()
            .with_stream_id(stream_id.clone())
            .with_event_types(vec!["TaskSubmitted".to_string()])
            .after_position(10)
            .limit(100);

        assert_eq!(filter.stream_id, Some(stream_id));
        assert_eq!(filter.event_types, vec!["TaskSubmitted"]);
        assert_eq!(filter.after_position, Some(10));
        assert_eq!(filter.limit, Some(100));
    }

    #[test]
    fn test_event_snapshot_creation() {
        let stream_id = StreamId::new("task", "123");
        let snapshot = EventSnapshot::new(
            stream_id.clone(),
            100,
            serde_json::json!({"status": "completed"}),
        );

        assert_eq!(snapshot.stream_id, stream_id);
        assert_eq!(snapshot.stream_category, "task");
        assert_eq!(snapshot.stream_position, 100);
    }

    #[test]
    fn test_roundtrip_stream_id() {
        let original_task_id = TaskId::generate();
        let aggregate_id = AggregateId::Task(original_task_id);

        // Convert to StreamId
        let stream_id = StreamId::from_aggregate_id(&aggregate_id);

        // Convert back to AggregateId
        let converted = stream_id.to_aggregate_id().unwrap();

        assert_eq!(aggregate_id, converted);
    }
}
